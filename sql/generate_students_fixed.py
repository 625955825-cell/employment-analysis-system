def cleanup_batch_students(conn, cursor):
    """清理本次批量导入的学生数据（按 remark 标记 + 关联表，JOIN DELETE 方式）"""
    try:
        cursor.execute("SELECT COUNT(*) FROM sys_user WHERE remark = '批量导入学生'")
        deleted_user = cursor.fetchone()[0]
        if deleted_user == 0:
            print("✓ 清理完成：没有找到残留数据")
            return

        # 按依赖顺序清理关联表（先删子表再删父表）
        cleanup_sqls = [
            # interview_invitation
            ("DELETE ia FROM interview_invitation ia JOIN sys_user su ON ia.student_id = su.id WHERE su.remark = '批量导入学生'", "interview_invitation"),
            # offer_letter
            ("DELETE ol FROM offer_letter ol JOIN sys_user su ON ol.student_id = su.id WHERE su.remark = '批量导入学生'", "offer_letter"),
            # job_application
            ("DELETE ja FROM job_application ja JOIN sys_user su ON ja.student_id = su.id WHERE su.remark = '批量导入学生'", "job_application"),
            # employment_attachment（通过 employment_record 关联）
            ("DELETE ea FROM employment_attachment ea JOIN employment_record er ON ea.employment_id = er.id JOIN sys_user su ON er.student_id = su.id WHERE su.remark = '批量导入学生'", "employment_attachment"),
            # employment_record
            ("DELETE er FROM employment_record er JOIN sys_user su ON er.student_id = su.id WHERE su.remark = '批量导入学生'", "employment_record"),
            # tripartite_agreement
            ("DELETE ta FROM tripartite_agreement ta JOIN sys_user su ON ta.student_id = su.id WHERE su.remark = '批量导入学生'", "tripartite_agreement"),
            # conversation_record
            ("DELETE cr FROM conversation_record cr JOIN sys_user su ON cr.student_id = su.id WHERE su.remark = '批量导入学生'", "conversation_record"),
            # student_resume
            ("DELETE sr FROM student_resume sr JOIN sys_user su ON sr.student_id = su.id WHERE su.remark = '批量导入学生'", "student_resume"),
            # student_info
            ("DELETE si FROM student_info si JOIN sys_user su ON si.user_id = su.id WHERE su.remark = '批量导入学生'", "student_info"),
            # sys_user_role
            ("DELETE sur FROM sys_user_role sur JOIN sys_user su ON sur.user_id = su.id WHERE su.remark = '批量导入学生'", "sys_user_role"),
            # sys_user（最后删）
            ("DELETE FROM sys_user WHERE remark = '批量导入学生'", "sys_user"),
        ]

        deleted_counts = {}
        for sql, tbl in cleanup_sqls:
            cursor.execute(sql)
            cnt = cursor.rowcount
            if cnt > 0:
                deleted_counts[tbl] = cnt

        conn.commit()

        print(f"✓ 清理完成：删除了 {deleted_user} 个账号")
        for tbl, cnt in deleted_counts.items():
            print(f"    - {tbl}: {cnt} 条")
    except Exception as e:
        print(f"⚠ 清理时出错: {e}")
        conn.rollback()


